"""Generic, permission-scoped table reading (table_describe, table_read) – no free SQL (that is tools_sql).

The agent picks table, columns, filters, sort, grouping/aggregates; the server builds the SQL. Identifiers come
only from tabele_katalog.json (generated by scripts/gen_tabele.py, [TAJNO] columns absent); every value goes to
MySQL as a %s parameter. Each area needs jsi:tabele:<area>; columns marked pii need jsi:kandidati:pii in every
role (select, filter, group, sort), so their content cannot leak through a filter either.
"""
from __future__ import annotations

import functools
import json
import os
from typing import Any

from . import db
from .config import Config
from .permissions import KANDIDATI_PII, Principal, require
from .tools_read import DATA_NOTE, InputError, _page_info

LIMIT_DEFAULT = 50
LIMIT_MAX = 1000
IN_MAX = 500
OPS = {"eq": "=", "ne": "<>", "lt": "<", "le": "<=", "gt": ">", "ge": ">=", "in": "IN", "not_in": "NOT IN",
       "like": "LIKE", "is_null": "IS NULL", "not_null": "IS NOT NULL", "between": "BETWEEN"}
AGG = {"count": "COUNT", "count_distinct": "COUNT(DISTINCT", "sum": "SUM", "avg": "AVG", "min": "MIN", "max": "MAX"}


@functools.lru_cache(maxsize=1)
def catalog() -> dict:
    with open(os.path.join(os.path.dirname(__file__), "tabele_katalog.json"), encoding="utf-8") as f:
        return json.load(f)


def _table(name: str) -> tuple[str, dict, dict]:
    for key, area in catalog()["podrucja"].items():
        if name in area["tabele"]:
            return key, area, area["tabele"][name]
    raise InputError(f"Tabelle nicht freigegeben / tabela nije dostupna: {name!r} – siehe table_describe")


def _q(ident: str) -> str:
    return f"`{ident}`"  # identifiers are whitelisted before they reach here


def area_permissions(area: dict, entry: dict | None = None) -> list[str]:
    perms = [area["permission"]]
    if entry and entry.get("dodatna_permission"):
        perms.append(entry["dodatna_permission"])
    return perms


def table_describe(cfg: Config, p: Principal, podrucje: str | None = None, tabela: str | None = None) -> dict:
    cat = catalog()["podrucja"]
    pii_ok = p.has(KANDIDATI_PII)
    if tabela:
        key, area, entry = _table(tabela)
        require(p, area_permissions(area, entry))
        cols = [{"kolona": c, "tip": m["tip"], "opis": m["opis"], "pii": m["pii"]} for c, m in entry["kolone"].items()]
        return {"podrucje": key, "tabela": tabela, "redova_cca": entry["redova_cca"], "pk": entry["pk"], "kolone": cols,
                "napomena": ("Kolone s pii=true samo uz pii=true i ovlaštenje jsi:kandidati:pii."
                             + ("" if pii_ok else " Ti nemaš to ovlaštenje.")
                             + " [TAJNO] kolone nisu uopće navedene.")}
    out = []
    for key, area in cat.items():
        if podrucje and key != podrucje:
            continue
        allowed = p.has(area["permission"])
        tabs = ([{"tabela": t, "redova_cca": e["redova_cca"], "kolona": len(e["kolone"]),
                  "pii_kolona": sum(1 for m in e["kolone"].values() if m["pii"])} for t, e in area["tabele"].items()]
                if allowed else None)
        out.append({"podrucje": key, "naziv": area["naziv"], "permission": area["permission"], "dozvoljeno": allowed,
                    "broj_tabela": len(area["tabele"]), "tabele": tabs})
    if podrucje and not out:
        raise InputError(f"podrucje unbekannt; erlaubt: {sorted(cat)}")
    return {"podrucja": out, "pii_dozvoljeno": pii_ok,
            "napomena": "Detalji jedne tabele: table_describe(tabela=...). Čitanje: table_read. Stanje šeme 2026-10-29."}


def _col(entry: dict, name: Any, pii_ok: bool, what: str) -> str:
    if not isinstance(name, str) or name not in entry["kolone"]:
        raise InputError(f"{what}: Spalte {name!r} nicht in dieser Tabelle freigegeben / kolona nije dostupna")
    if entry["kolone"][name]["pii"] and not pii_ok:
        raise InputError(f"{what}: Spalte {name!r} enthält Personendaten – nur mit pii=true und jsi:kandidati:pii")
    return name


def _where(entry: dict, filteri: list[dict] | None, pii_ok: bool) -> tuple[str, list]:
    if not filteri:
        return "", []
    if not isinstance(filteri, list) or len(filteri) > 20:
        raise InputError("filteri: Liste mit höchstens 20 Bedingungen")
    parts, params = [], []
    for f in filteri:
        if not isinstance(f, dict):
            raise InputError("filteri: jeder Eintrag {kolona, op, vrijednost}")
        col = _q(_col(entry, f.get("kolona"), pii_ok, "filter"))
        op = f.get("op", "eq")
        if op not in OPS:
            raise InputError(f"filter op {op!r} unbekannt; erlaubt: {sorted(OPS)}")
        v = f.get("vrijednost")
        if op in ("is_null", "not_null"):
            parts.append(f"{col} {OPS[op]}")
        elif op in ("in", "not_in"):
            if not isinstance(v, list) or not 1 <= len(v) <= IN_MAX:
                raise InputError(f"filter {op}: Liste mit 1..{IN_MAX} Werten")
            parts.append(f"{col} {OPS[op]} (" + ", ".join(["%s"] * len(v)) + ")")
            params += v
        elif op == "between":
            if not isinstance(v, list) or len(v) != 2:
                raise InputError("filter between: [von, bis]")
            parts.append(f"{col} BETWEEN %s AND %s")
            params += v
        elif op == "like":
            if not isinstance(v, str) or not v.strip() or len(v) > 100:
                raise InputError("filter like: Text 1..100 Zeichen (Teilstring, ohne Platzhalter)")
            parts.append(f"{col} LIKE %s")
            params.append("%" + v.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%")
        else:
            if v is None or isinstance(v, (list, dict)):
                raise InputError(f"filter {op}: einzelner Wert erwartet (für NULL: is_null)")
            parts.append(f"{col} {OPS[op]} %s")
            params.append(v)
    return " WHERE " + " AND ".join(parts), params


def table_read(cfg: Config, p: Principal, tabela: str, kolone: list[str] | None = None,
               filteri: list[dict] | None = None, grupiraj_po: list[str] | None = None,
               agregati: list[dict] | None = None, sortiraj: list[dict] | None = None,
               limit: int | None = None, offset: int | None = None, pii: bool = False) -> dict:
    key, area, entry = _table(tabela)
    require(p, area_permissions(area, entry))
    if pii:
        require(p, [KANDIDATI_PII])
    pii_ok = bool(pii)
    lim = LIMIT_DEFAULT if limit is None else limit
    off = 0 if offset is None else offset
    if isinstance(lim, bool) or not isinstance(lim, int) or not 1 <= lim <= LIMIT_MAX:
        raise InputError(f"limit muss 1..{LIMIT_MAX} sein")
    if isinstance(off, bool) or not isinstance(off, int) or not 0 <= off <= 10_000_000:
        raise InputError("offset muss 0..10000000 sein")
    where, params = _where(entry, filteri, pii_ok)
    t = _q(tabela)
    grouped = bool(grupiraj_po or agregati)
    hidden = []
    if grouped:
        groups = [_col(entry, c, pii_ok, "grupiraj_po") for c in (grupiraj_po or [])]
        if len(groups) > 5:
            raise InputError("grupiraj_po: höchstens 5 Spalten")
        sel, aliases = [_q(g) for g in groups], set(groups)
        for a in (agregati or [{"fn": "count"}]):
            fn = (a or {}).get("fn")
            if fn not in AGG:
                raise InputError(f"agregat fn {fn!r} unbekannt; erlaubt: {sorted(AGG)}")
            if fn == "count" and not a.get("kolona"):
                sel.append("COUNT(*) AS `broj`")
                aliases.add("broj")
                continue
            c = _col(entry, a.get("kolona"), pii_ok, "agregat")
            alias = f"{fn}_{c}"
            sel.append(f"{AGG[fn]}({_q(c)}){')' if fn == 'count_distinct' else ''} AS {_q(alias)}")
            aliases.add(alias)
        group_sql = (" GROUP BY " + ", ".join(_q(g) for g in groups)) if groups else ""
        order = []
        for s in (sortiraj or []):
            c = (s or {}).get("kolona")
            if c not in aliases:
                raise InputError(f"sortiraj: im Gruppenmodus nur nach {sorted(aliases)}")
            order.append(f"{_q(c)} {'DESC' if s.get('smjer') == 'desc' else 'ASC'}")
        order_sql = " ORDER BY " + ", ".join(order or [_q(g) for g in groups] or ["1"])
        sql = f"SELECT {', '.join(sel)} FROM {t}{where}{group_sql}{order_sql} LIMIT %s OFFSET %s"
        count_sql = (f"SELECT COUNT(*) AS n FROM (SELECT 1 FROM {t}{where}{group_sql}) x" if groups
                     else None)
        unit = "grupa"
    else:
        if kolone:
            if not isinstance(kolone, list) or len(kolone) > 60:
                raise InputError("kolone: Liste mit höchstens 60 Spalten")
            cols = [_col(entry, c, pii_ok, "kolone") for c in dict.fromkeys(kolone)]
        else:
            cols = [c for c, m in entry["kolone"].items() if pii_ok or not m["pii"]]
            hidden = [c for c, m in entry["kolone"].items() if m["pii"] and not pii_ok]
        order = []
        for s in (sortiraj or []):
            order.append(f"{_q(_col(entry, (s or {}).get('kolona'), pii_ok, 'sortiraj'))} "
                         f"{'DESC' if (s or {}).get('smjer') == 'desc' else 'ASC'}")
        order += [f"{_q(k)} ASC" for k in entry["pk"] if f"{_q(k)} ASC" not in order and f"{_q(k)} DESC" not in order]
        order_sql = (" ORDER BY " + ", ".join(order)) if order else ""
        sql = f"SELECT {', '.join(_q(c) for c in cols)} FROM {t}{where}{order_sql} LIMIT %s OFFSET %s"
        count_sql = f"SELECT COUNT(*) AS n FROM {t}{where}"
        unit = "redova"
    rows = db.query(cfg, sql, tuple(params) + (lim, off))
    notes = []
    total: int | None
    if count_sql is None:
        total = len(rows) + off  # aggregate over the whole table without GROUP BY: exactly one row
    else:
        try:
            total = int(db.query(cfg, count_sql, tuple(params))[0]["n"])
        except db.DbError:
            total = None
            notes.append("Ukupan broj nije izračunat (timeout) – suzi filter.")
    if hidden:
        notes.append(f"{len(hidden)} kolona s ličnim podacima izostavljeno (pii=true + jsi:kandidati:pii): {', '.join(hidden)}.")
    page = _page_info(total, off, len(rows), unit, more=len(rows) == lim if total is None else None)
    if total is not None and page["ima_jos"]:
        page["sljedeci_offset"] = off + len(rows)
    return {"podrucje": key, "tabela": tabela, "rezultat": rows, "broj_redova": len(rows), "stranica": page,
            "napomene": notes, "stanje_podataka": DATA_NOTE}
