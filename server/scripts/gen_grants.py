"""Generate MySQL GRANT statements for the JSI-MCP database users.

- read-only user: SELECT on all 190 tables, [TAJNO] columns excluded via column-level SELECT.
- mirror write user: read-only grants + INSERT/UPDATE exactly on the write-registry columns,
  INSERT on mcp_aenderung/mcp_fehler, INSERT + UPDATE(lsp_broj_dana) on idk_log_statusi_prijave.
No DELETE, DROP, ALTER, CREATE anywhere.

Usage: python3 -I scripts/gen_grants.py readonly|write <db_name> <user> [host] > grants.sql
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(ROOT, "src"))

from jsi_mcp.registry import REGISTRY  # noqa: E402
from jsi_mcp.sensitive import SENSITIVE  # noqa: E402


def tables():
    rows = json.load(open(os.path.join(ROOT, "..", "docs", "rohdaten", "columns.json"), encoding="utf-8"))["rows"]
    out = {}
    for r in rows:
        out.setdefault(r["t"], []).append((int(r["pos"]), r["col"]))
    return {t: [c for _, c in sorted(v)] for t, v in out.items()}


def q(name):
    return f"`{name}`"


def read_grants(db, who):
    out = []
    for t, cols in sorted(tables().items()):
        bad = SENSITIVE.get(t, frozenset())
        if bad:
            ok = [c for c in cols if c not in bad]
            out.append(f"GRANT SELECT ({', '.join(q(c) for c in ok)}) ON {q(db)}.{q(t)} TO {who};")
        else:
            out.append(f"GRANT SELECT ON {q(db)}.{q(t)} TO {who};")
    return out


def write_grants(db, who):
    ins, upd = {}, {}
    for e in REGISTRY.values():
        cols = set(e.columns)
        if "create" in e.actions:
            ins.setdefault(e.table, set()).update(cols | set(e.create_defaults) | set(e.fixed))
        if "update" in e.actions or "archive" in e.actions:
            upd.setdefault(e.table, set()).update({c for c in cols if not e.columns[c].create_only} | set(e.archive))
    # set_application_status side effects
    upd.setdefault("idk_kandidati", set()).update({"kandidat_status_prijave", "kandidat_latest_reserved_time"})
    ins["idk_log_statusi_prijave"] = {"lsp_kandidat_id", "lsp_projekt_id", "lsp_status_prijave_id", "lsp_employee_id",
                                      "lsp_izvor", "lsp_datetime", "lsp_broj_dana"}
    upd["idk_log_statusi_prijave"] = {"lsp_broj_dana"}
    ins["mcp_aenderung"] = {"a_zeit", "a_werkzeug", "a_aktion", "a_tabelle", "a_datensatz_id", "a_vorher", "a_nachher",
                            "a_kandidat_id", "a_art", "a_zustand", "a_freigabe_code", "a_freigabe_zeit", "a_ausgefuehrt_zeit", "a_notiz"}
    ins["mcp_fehler"] = {"f_zeit", "f_werkzeug", "f_art", "f_meldung", "f_kontext"}
    out = []
    for t in sorted(ins):
        bad = ins[t] & SENSITIVE.get(t, frozenset())
        assert not bad, (t, bad)
        out.append(f"GRANT INSERT ({', '.join(q(c) for c in sorted(ins[t]))}) ON {q(db)}.{q(t)} TO {who};")
    for t in sorted(upd):
        bad = upd[t] & SENSITIVE.get(t, frozenset())
        assert not bad, (t, bad)
        out.append(f"GRANT UPDATE ({', '.join(q(c) for c in sorted(upd[t]))}) ON {q(db)}.{q(t)} TO {who};")
    return out


def main(argv):
    if len(argv) < 3 or argv[0] not in ("readonly", "write"):
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    mode, db, user = argv[0], argv[1], argv[2]
    host = argv[3] if len(argv) > 3 else "%"
    who = f"'{user}'@'{host}'"
    print(f"-- generated by scripts/gen_grants.py ({mode}); create the user first, e.g.:")
    print(f"-- CREATE USER {who} IDENTIFIED BY '<set-in-db-admin-console>' REQUIRE SSL;")
    for line in read_grants(db, who) + (write_grants(db, who) if mode == "write" else []):
        print(line)


if __name__ == "__main__":
    main(sys.argv[1:])
